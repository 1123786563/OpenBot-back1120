def gh(*args):
    return subprocess.check_output(['gh', *args], text=True)

def api(path, payload=None):
    args=['api',path]
    if payload is not None:
        args += ['--method','POST','--input','-']
    p=subprocess.run(['gh',*args],input=json.dumps(payload) if payload is not None else None,
                     text=True,capture_output=True)
    if p.returncode: raise RuntimeError(p.stderr)
    return json.loads(p.stdout) if p.stdout.strip() else None

def main():
    assert json.loads(gh('repo','view','--json','nameWithOwner'))['nameWithOwner']==REPO
    state=json.loads(STATE.read_text()) if STATE.exists() else {'issues':{},'verified':False}
    def save(): STATE.write_text(json.dumps(state,ensure_ascii=False,indent=2)+'\n')
    known={}
    def issue(number):
        if number not in known: known[number]=api(f'repos/{REPO}/issues/{number}')
        return known[number]
    def resolve(dep):
        return state['issues'][dep]['number'] if isinstance(dep,str) else dep
    # All new-task prerequisites precede their dependents.
    completed=set()
    for t in TASKS:
        assert all(not isinstance(d,str) or d in completed for d in t['deps'])
        completed.add(t['key'])
    work=ROOT/'billing-subtasks'
    work.mkdir(exist_ok=True)
    existing=api(f'repos/{REPO}/issues?state=all&per_page=100')
    for index,t in enumerate(TASKS,1):
        deps=[resolve(d) for d in t['deps']]
        title=f'[计费 {index:02d}/20] '+t['title']
        deptext=', '.join(f'#{n}' for n in deps) or '无任务前置'
        body=f"Part of #61\n\nBlocked by: {deptext}\n\n## What to build\n\n{t['goal']}\n\n## 实施边界与当前状态\n\n{t['scope']}\n\n## 阻塞关与解除条件\n\n{t['gate']}\n\n"
        if deps: body+='只有上述前置任务验收完成后才进入本票正式实施；可以提前阅读和准备夹具，但不能用提前准备关闭本票。\n\n'
        body+='## Acceptance criteria\n\n'+'\n'.join('- [ ] '+x for x in t['criteria'])+'\n'+COMMON
        path=work/(t['key']+'.md'); path.write_text(body)
        if t['key'] not in state['issues']:
            matches=[x for x in existing if x['title']==title]
            assert len(matches)<=1
            if matches:
                remote=matches[0]
                assert remote['body'].strip()==body.strip(), 'Existing task differs; inspect before reuse'
            else:
                url=gh('issue','create','--repo',REPO,'--title',title,'--body-file',str(path),'--label','ready-for-agent').strip()
                number=int(url.rsplit('/',1)[1]); remote=issue(number)
            state['issues'][t['key']]={'number':remote['number'],'id':remote['id'],'url':remote['html_url'],'title':title,'dependencies':deps}
            save()
        entry=state['issues'][t['key']]
        subs=api(f'repos/{REPO}/issues/61/sub_issues?per_page=100')
        if entry['id'] not in {x['id'] for x in subs}:
            api(f'repos/{REPO}/issues/61/sub_issues',{'sub_issue_id':entry['id']})
        current=api(f"repos/{REPO}/issues/{entry['number']}/dependencies/blocked_by?per_page=100")
        for number in deps:
            if number not in {x['number'] for x in current}:
                api(f"repos/{REPO}/issues/{entry['number']}/dependencies/blocked_by",{'issue_id':issue(number)['id']})
        print(f"Published {t['key']} #{entry['number']}; dependencies {deptext}",flush=True)
    save()

