#!/usr/bin/env bash
# Pin the three T01 images to immutable digests and write versions.lock.
# A floating tag (backend-images.env defaults OPENBOT_BACKEND_TAG=main) is not
# an acceptable version for T01 (requirement AC-02).
set -Eeuo pipefail
source "$(dirname "$0")/lib/common.sh"

t01_require_docker

# Casdoor baseline carried over from docker-compose.casdoor.yml (already pinned
# there); re-resolved here against the local pull so the lock reflects what we
# actually run, not what a file claims.
CASDOOR_PIN="casbin/casdoor-all-in-one@sha256:710df7fcb2d05ddc590cf78a6862ec61026a140c1a02ec6a40392dc24dabf7f9"
SERVER_TAG="${T01_SERVER_TAG:-main}"
PGVECTOR_TAG="${T01_PGVECTOR_TAG:-pg17}"

resolve_digest() { # repo:tag -> repo@sha256:...
  local ref="$1" digest
  t01_info "pin" "pulling ${ref}"
  docker pull --quiet "$ref" >/dev/null ||
    t01_fail "pin" "could not pull ${ref} (check ghcr.io/docker hub access and credentials)."
  digest="$(docker image inspect --format '{{index .RepoDigests 0}}' "$ref")" ||
    t01_fail "pin" "pulled ${ref} but it has no registry digest (never pushed?)."
  [ -n "$digest" ] || t01_fail "pin" "empty digest for ${ref}."
  echo "$digest"
}

SERVER_PIN="$(resolve_digest "ghcr.io/copilotkit/openbot:${SERVER_TAG}")"
PGVECTOR_PIN="$(resolve_digest "pgvector/pgvector:${PGVECTOR_TAG}")"
CASDOOR_RESOLVED="$(resolve_digest "casbin/casdoor-all-in-one:latest-all-in-one" 2>/dev/null || echo "$CASDOOR_PIN")"

{
  echo "# Generated by scripts/t01/00-pin-images.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit by hand."
  echo "# Source tag for the server image: ${SERVER_TAG} (from backend-images.env default or T01_SERVER_TAG)."
  echo "T01_SERVER_IMAGE=${SERVER_PIN}"
  echo "T01_CASDOOR_IMAGE=${CASDOOR_RESOLVED}"
  echo "T01_PGVECTOR_IMAGE=${PGVECTOR_PIN}"
} >"$T01_VERSIONS_LOCK" ||
  t01_fail "pin" "could not write $T01_VERSIONS_LOCK"

t01_info "pin" "wrote $T01_VERSIONS_LOCK:"
cat "$T01_VERSIONS_LOCK"

# Record the Casdoor binary's own reported version for the report (AC-10).
t01_info "pin" "casdoor image labels:"
docker image inspect --format '{{json .Config.Labels}}' "${CASDOOR_RESOLVED%%@*}" 2>/dev/null || true

# Print the compose override values the other scripts expect in .env.t01.
t01_info "pin" "now set in .env.t01 (values only, no secrets):"
sed -n 's/^T01_\(SERVER_IMAGE\|CASDOOR_IMAGE\|PGVECTOR_IMAGE\)=/T01_\1=/p' "$T01_VERSIONS_LOCK" >&2
