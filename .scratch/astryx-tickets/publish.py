statepath=root/'published.json'
state=json.loads(statepath.read_text()) if statepath.exists() else {}
for i,(title,deps,what,criteria) in enumerate(tickets,1):
    key=str(i)
    if key in state: continue
    blockers=[state[str(d)]['number'] for d in deps]
    body='## Parent\n\nPart of #40\n\n## What to build\n\n'+what+'\n\n范围限于 Web UI，遵循父 spec 与 ADR 0001；保留业务/API/权限语义。每票包含实现和行为验证，不另拆测试票。\n\n## Acceptance criteria\n\n'+ '\n'.join('- [ ] '+c for c in criteria)
    body+='\n- [ ] 对本票改动运行相关行为测试、Web 类型检查及生产构建，记录实际结果；不以组件内部 DOM 或生成类名作为断言。\n'
    body+='\n## Blocked by\n\n'+ ('\n'.join(f'- #{n}' for n in blockers) if blockers else 'None (can start immediately).')
    body+='\n\n仅在所有阻塞票完成后启动。第 3 票须获得用户明确视觉认可才算完成，后续票不得绕过该门槛。\n'
    p=root/f'{i:02}.md';p.write_text(body)
    url=gh('issue','create','--repo',repo,'--title',f'[Astryx {i:02}/20] {title}','--body-file',str(p),'--label','ready-for-agent')
    number=int(url.rsplit('/',1)[1]); obj=api(f'issues/{number}')
    state[key]={'number':number,'id':obj['id'],'url':url,'deps':deps}
    statepath.write_text(json.dumps(state,indent=2))
    print(f'Created {i:02}: {url}',flush=True)
for i,entry in state.items():
    if not entry.get('parent_linked'):
        api('issues/40/sub_issues','-X','POST','-F',f"sub_issue_id={entry['id']}")
        entry['parent_linked']=True; statepath.write_text(json.dumps(state,indent=2))
    linked=entry.setdefault('linked_deps',[])
    for d in entry['deps']:
        if d in linked: continue
        api(f"issues/{entry['number']}/dependencies/blocked_by",'-X','POST','-F',f"issue_id={state[str(d)]['id']}")
        linked.append(d);statepath.write_text(json.dumps(state,indent=2))
    print(f"Linked {i}: #{entry['number']}",flush=True)
