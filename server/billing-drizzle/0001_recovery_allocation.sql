-- =============================================================================
-- THE v1 -> v2 quota backfill.
--
-- Replays every PRE-upgrade restoration in commit order against the per-line
-- capacity each original deduction line owns (its delta_consumed):
--
--   * positive adjustments  -> amount = adjustment.signed_delta_microcredits,
--     restoring event = the adjustment's own ledger_event (adjustment_id);
--   * direct compensation grants -> amount = the compensation lot's
--     granted_microcredits, restoring event = the grant's own ledger_event
--     (the granted line on that lot).
--
-- Each restoration fills the deduction's lines greedily (lot_id order,
-- per-line capacity never exceeded) and lands as recovery_allocation rows
-- carrying the ORIGINAL business ids: restoration_event_id keeps pointing at
-- the historical grant/adjustment event, so business identities, outbox
-- records, idempotency first results and history are untouched — only the
-- NEW quota ledger learns what the old code already spent.
--
-- A deduction whose history demands more than it ever consumed (v1 could
-- double-restore an expired source lot), or whose restoring history cannot
-- be identified, gets a recovery_block row instead of a guess: every later
-- recovery attempt for it is refused by the service and by the database
-- guard, and the decision stays auditable in recovery_backfill_audit.
--
-- Runs ONCE, inside this migration's own transaction: a crashed upgrade
-- leaves either nothing or the complete backfill. Re-running the migrator
-- against an upgraded database never re-executes it (migration journal).
-- =============================================================================
DO $backfill$
DECLARE
	ev RECORD;
	rec RECORD;
	cap RECORD;
	v_capacity bigint;
	v_demanded bigint;
	v_allocated bigint;
	v_left bigint;
	v_take bigint;
	v_count integer;
	v_block_reason text;
	v_detail jsonb;
	v_first_us bigint;
	v_now bigint := (EXTRACT(EPOCH FROM clock_timestamp()) * 1000000)::bigint;
BEGIN
	CREATE TEMP TABLE bf_capacity ON COMMIT DROP AS
	SELECT event_id, lot_id,
	       delta_consumed_microcredits AS capacity,
	       delta_consumed_microcredits AS remaining
	FROM billing.ledger_line
	WHERE delta_consumed_microcredits > 0;

	CREATE TEMP TABLE bf_restoration ON COMMIT DROP AS
	SELECT a.organization_id, a.account_id, a.original_event_id,
	       a.signed_delta_microcredits AS amount,
	       'adjustment'::text AS restored_via,
	       (SELECT le.id FROM billing.ledger_event le
	         WHERE le.adjustment_id = a.id
	         ORDER BY le.committed_at_us, le.id LIMIT 1) AS restoration_event_id,
	       a.created_at_us AS committed_at_us
	FROM billing.adjustment a
	WHERE a.signed_delta_microcredits > 0
	UNION ALL
	SELECT cl.organization_id, cl.account_id, cl.compensation_for_event_id,
	       cl.granted_microcredits,
	       'credit_grant'::text,
	       (SELECT ll.event_id FROM billing.ledger_line ll
	         WHERE ll.lot_id = cl.id AND ll.delta_granted_microcredits > 0
	         ORDER BY ll.created_at_us, ll.event_id LIMIT 1),
	       cl.created_at_us
	FROM billing.credit_lot cl
	WHERE cl.compensation_for_event_id IS NOT NULL
	  -- a 30-day lot an ADJUSTMENT issued for an expired share is already
	  -- counted through that adjustment's signed_delta; counting it here too
	  -- would double the demanded quota. Only lots issued by the direct
	  -- compensation GRANT entry (never referenced as an adjustment's
	  -- compensation_lot_id) speak for the grant path.
	  AND NOT EXISTS (
	    SELECT 1 FROM billing.adjustment a WHERE a.compensation_lot_id = cl.id);

	FOR ev IN
		SELECT DISTINCT organization_id, account_id, original_event_id FROM bf_restoration
	LOOP
		SELECT COALESCE(SUM(remaining), 0) INTO v_capacity
		FROM bf_capacity WHERE event_id = ev.original_event_id;
		v_demanded := 0;
		v_allocated := 0;
		v_count := 0;
		v_block_reason := NULL;
		v_detail := '[]'::jsonb;
		v_first_us := NULL;
		FOR rec IN
			SELECT * FROM bf_restoration
			WHERE organization_id = ev.organization_id
			  AND account_id = ev.account_id
			  AND original_event_id = ev.original_event_id
			ORDER BY committed_at_us, restoration_event_id NULLS LAST
		LOOP
			EXIT WHEN v_block_reason IS NOT NULL;
			v_count := v_count + 1;
			IF v_first_us IS NULL THEN v_first_us := rec.committed_at_us; END IF;
			IF rec.restoration_event_id IS NULL THEN
				v_block_reason := 'unattributable_history';
				v_detail := v_detail || jsonb_build_object(
					'stopped_at_restoration_ordinal', v_count,
					'reason_detail', 'the restoring ledger event could not be identified');
				EXIT;
			END IF;
			v_demanded := v_demanded + rec.amount;
			v_left := rec.amount;
			FOR cap IN
				SELECT c.lot_id, c.remaining FROM bf_capacity c
				WHERE c.event_id = ev.original_event_id AND c.remaining > 0
				ORDER BY c.lot_id
				FOR UPDATE
			LOOP
				EXIT WHEN v_left = 0;
				v_take := LEAST(cap.remaining, v_left);
				INSERT INTO billing.recovery_allocation
					(organization_id, account_id, original_event_id, original_lot_id,
					 restored_microcredits, restored_via, restoration_event_id, created_at_us)
				VALUES (ev.organization_id, ev.account_id, ev.original_event_id, cap.lot_id,
				        v_take, rec.restored_via, rec.restoration_event_id, rec.committed_at_us);
				UPDATE bf_capacity SET remaining = remaining - v_take
				WHERE event_id = ev.original_event_id AND lot_id = cap.lot_id;
				v_allocated := v_allocated + v_take;
				v_left := v_left - v_take;
			END LOOP;
			IF v_left > 0 THEN
				v_block_reason := 'over_refunded_history';
				v_detail := v_detail || jsonb_build_object(
					'stopped_at_restoration_ordinal', v_count,
					'unhonoured_microcredits', v_left,
					'restoration_event_id', rec.restoration_event_id,
					'restored_via', rec.restored_via);
			END IF;
		END LOOP;

		IF v_count = 0 THEN
			RAISE EXCEPTION 'backfill invariant broken: deduction % queued with no restoration', ev.original_event_id;
		END IF;

		IF v_block_reason IS NOT NULL THEN
			INSERT INTO billing.recovery_block
				(organization_id, account_id, original_event_id, reason,
				 deduction_total, demanded_total, detail, created_at_us)
			VALUES (ev.organization_id, ev.account_id, ev.original_event_id, v_block_reason,
			        v_capacity, v_demanded, v_detail, v_now);
		END IF;
		INSERT INTO billing.recovery_backfill_audit
			(organization_id, account_id, original_event_id, mode,
			 restored_total, deduction_total, restoration_count, detail, created_at_us)
		VALUES (ev.organization_id, ev.account_id, ev.original_event_id,
		        CASE WHEN v_block_reason IS NULL THEN 'attributed' ELSE 'blocked' END,
		        v_allocated, v_capacity, v_count,
		        jsonb_build_object(
		          'demanded_total', v_demanded,
		          'block_reason', v_block_reason,
		          'first_restoration_at_us', v_first_us) || v_detail,
		        v_now);
	END LOOP;
END
$backfill$;
