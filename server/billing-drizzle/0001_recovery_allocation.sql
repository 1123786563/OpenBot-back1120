-- =============================================================================
-- Upgrade bookkeeping for the v1 -> v2 recovery-quota upgrade.
--
-- The v1 ledger already committed restorations (positive adjustments and
-- direct compensation grants) WITHOUT the per-line recovery_allocation quota
-- ledger. This migration closes that gap in two steps:
--
--   1. `recovery_block` — the audit-visible closure for a deduction whose
--      historical restorations CANNOT be attributed reliably (restoring
--      history missing, or the history restored more than the deduction ever
--      consumed). While a row exists here, the service AND the database
--      quota guard refuse ANY further recovery for that deduction: an
--      already over-restored deduction can never be restored again under a
--      new business key.
--   2. `recovery_backfill_audit` — one auditable decision per deduction that
--      carried pre-upgrade restorations: what the history demanded, what the
--      deduction lines could absorb, and where a closure had to stop.
--
-- Both are append-only migration-time objects; the immutability triggers for
-- them are installed by the migrator's hardening phase like every other
-- append-only object.
-- =============================================================================
CREATE TABLE "billing"."recovery_block" (
	"organization_id" uuid NOT NULL,
	"account_id" uuid NOT NULL,
	"original_event_id" uuid NOT NULL,
	"reason" text NOT NULL,
	"deduction_total" bigint NOT NULL,
	"demanded_total" bigint NOT NULL,
	"detail" jsonb NOT NULL,
	"created_at_us" bigint NOT NULL,
	CONSTRAINT "billing_recovery_block_pk" PRIMARY KEY("organization_id","account_id","original_event_id"),
	CONSTRAINT "billing_recovery_block_reason_check" CHECK(length("billing"."recovery_block"."reason") > 0),
	CONSTRAINT "billing_recovery_block_account_fk" FOREIGN KEY ("organization_id","account_id") REFERENCES "billing"."account"("organization_id","id") ON DELETE no action ON UPDATE no action,
	CONSTRAINT "billing_recovery_block_event_fk" FOREIGN KEY ("organization_id","account_id","original_event_id") REFERENCES "billing"."ledger_event"("organization_id","account_id","id") ON DELETE no action ON UPDATE no action
